import { realpathSync } from 'node:fs';

/** Where Xcode lives on a default install; remapping the active Xcode here makes builds independent of the Xcode install path. */
export const CANONICAL_DEVELOPER_DIR = '/Applications/Xcode.app/Contents/Developer';

export interface SettingsOptions {
	/** Absolute source root; every path below it is recorded relative to it. */
	root: string;
	/** Active DEVELOPER_DIR, remapped to {@link CANONICAL_DEVELOPER_DIR}. */
	developerDir?: string;
	strip: boolean;
	conciseMagicFile: boolean;
	libraryEvolution: boolean;
}

/**
 * Every spelling a tool may use for `path`. Xcode rewrites `/private/tmp/...` to `/tmp/...`
 * (and symlinked checkouts resolve differently), and a prefix map only matches the exact spelling.
 */
export function pathSpellings(path: string): string[] {
	const out = new Set<string>([stripTrailingSlash(path)]);
	try {
		out.add(stripTrailingSlash(realpathSync(path)));
	} catch {
		// Path may not exist yet (e.g. when only printing settings).
	}
	for (const p of [...out]) {
		if (p.startsWith('/private/')) out.add(p.slice('/private'.length));
		else if (/^\/(tmp|var|etc)(\/|$)/.test(p)) out.add(`/private${p}`);
	}
	return [...out].sort();
}

function stripTrailingSlash(p: string): string {
	return p.length > 1 && p.endsWith('/') ? p.slice(0, -1) : p;
}

/** Quotes one token of a list-type build setting (OTHER_CFLAGS etc.) when it contains spaces or quotes. */
export function quoteListToken(token: string): string {
	return /[\s"'\\]/.test(token) ? `"${token.replace(/(["\\])/g, '\\$1')}"` : token;
}

function prefixMaps(opts: SettingsOptions): Array<[from: string, to: string]> {
	const maps: Array<[string, string]> = [];
	if (opts.developerDir) {
		for (const d of pathSpellings(opts.developerDir)) if (d !== CANONICAL_DEVELOPER_DIR) maps.push([d, CANONICAL_DEVELOPER_DIR]);
	}
	for (const r of pathSpellings(opts.root)) maps.push([r, '.']);
	return maps;
}

/** `KEY=VALUE` build settings passed to every xcodebuild invocation. */
export function buildSettings(opts: SettingsOptions): string[] {
	const maps = prefixMaps(opts);
	const cflags = maps.map(([from, to]) => quoteListToken(`-ffile-prefix-map=${from}=${to}`));
	const swiftFlags = maps.flatMap(([from, to]) => ['-file-prefix-map', quoteListToken(`${from}=${to}`)]);
	// Swift otherwise emits DWARF skeleton units pointing at clang module caches (.pcm) inside
	// DerivedData; those paths are machine-specific and dsymutil can't follow them once remapped.
	swiftFlags.push('-Xfrontend', '-no-clang-module-breadcrumbs');

	const settings = [
		'SKIP_INSTALL=NO',
		'ONLY_ACTIVE_ARCH=NO',
		'CODE_SIGNING_ALLOWED=NO',
		'GCC_GENERATE_DEBUGGING_SYMBOLS=YES',
		'DEBUG_INFORMATION_FORMAT=dwarf-with-dsym',
		// With -gmodules, type info lives in .pcm files that dsymutil can't find once their paths
		// are remapped, so the dSYM silently loses it. Emit full type info into the objects instead.
		'CLANG_ENABLE_MODULE_DEBUGGING=NO',
		// The .swiftmodule (and the AST copy in the dSYM) otherwise embeds every -I/-F/VFS path.
		'SWIFT_SERIALIZE_DEBUGGING_OPTIONS=NO',
		// Explicit-module builds serialize the absolute path of every dependency module (e.g. the
		// SDK's prebuilt .swiftmodules inside the Xcode install) into the .swiftmodule, with no
		// prefix map applied (seen with Xcode 26.6). Implicit modules record none.
		'SWIFT_ENABLE_EXPLICIT_MODULES=NO',
		`OTHER_CFLAGS=$(inherited) ${cflags.join(' ')}`,
		`OTHER_SWIFT_FLAGS=$(inherited) ${swiftFlags.join(' ')}`,
	];
	if (opts.libraryEvolution) settings.push('BUILD_LIBRARY_FOR_DISTRIBUTION=YES');
	if (opts.conciseMagicFile) settings.push('SWIFT_UPCOMING_FEATURE_CONCISE_MAGIC_FILE=YES');
	if (opts.strip) {
		// Strip the debug map (N_OSO/N_AST stabs) after dsymutil ran: it only holds absolute
		// intermediate paths and is useless once the dSYM exists. Same as `xcodebuild archive`.
		settings.push('DEPLOYMENT_POSTPROCESSING=YES', 'STRIP_INSTALLED_PRODUCT=YES', 'STRIP_STYLE=debugging');
	}
	return settings;
}

export const BUILD_ENV: Readonly<Record<string, string>> = {
	// Zero the timestamps ar/libtool write into static archives.
	ZERO_AR_DATE: '1',
};

/**
 * An .xcconfig with the same settings, for projects that drive xcodebuild themselves.
 * Paths are left as build-setting references so the file is machine-independent.
 */
export function xcconfig(): string {
	const s = buildSettings({ root: '$(XCREPRO_ROOT)', developerDir: '$(DEVELOPER_DIR)', strip: true, conciseMagicFile: true, libraryEvolution: true }).filter(
		(line) => !line.startsWith('OTHER_CFLAGS=') && !line.startsWith('OTHER_SWIFT_FLAGS='),
	);
	return [
		'// Generated by `xcrepro xcconfig`. Settings for reproducible, path-independent builds.',
		'//',
		'// Usage:',
		'//   ZERO_AR_DATE=1 xcodebuild ... -xcconfig reproducible.xcconfig \\',
		'//     -derivedDataPath <somewhere under XCREPRO_ROOT> XCREPRO_ROOT=<absolute source root>',
		'//',
		'// Then run `xcrepro normalize <xcframework>` on the result: the binary UUIDs, dSYM',
		'// relocation maps and Info.plist ordering still need post-processing.',
		'// Unlike the CLI, this file cannot add the alternate spellings of a symlinked root',
		'// (e.g. /tmp vs /private/tmp); point XCREPRO_ROOT at the path Xcode sees.',
		'',
		'XCREPRO_ROOT = $(SRCROOT)',
		'',
		...s.map((line) => line.replace('=', ' = ')),
		'OTHER_CFLAGS = $(inherited) -ffile-prefix-map=$(DEVELOPER_DIR)=' + CANONICAL_DEVELOPER_DIR + ' -ffile-prefix-map=$(XCREPRO_ROOT)=.',
		'OTHER_SWIFT_FLAGS = $(inherited) -file-prefix-map $(DEVELOPER_DIR)=' + CANONICAL_DEVELOPER_DIR + ' -file-prefix-map $(XCREPRO_ROOT)=. -Xfrontend -no-clang-module-breadcrumbs',
		'',
	].join('\n');
}
